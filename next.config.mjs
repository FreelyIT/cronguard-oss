/** @type {import('next').NextConfig} */

// React needs eval() for its dev tooling only; production builds never do.
const isDev = process.env.NODE_ENV !== 'production'

// The self-hosted build loads nothing from third parties (fonts are local),
// so every directive stays on 'self'. Inline scripts and styles are required
// by Next's bootstrap and the inline-styled design system.
const contentSecurityPolicy = [
  "default-src 'self'",
  `script-src 'self' 'unsafe-inline'${isDev ? " 'unsafe-eval'" : ''}`,
  "style-src 'self' 'unsafe-inline'",
  "font-src 'self'",
  "img-src 'self' data: blob:",
  "connect-src 'self'",
  "worker-src 'self' blob:",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join('; ')

const nextConfig = {
  output: 'standalone',
  serverExternalPackages: ['better-sqlite3'],

  // No Strict-Transport-Security here: CronGuard OSS usually runs behind a
  // reverse proxy that terminates TLS, and that proxy is where HSTS belongs.
  async headers() {
    return [
      {
        source: '/:path*',
        headers: [
          { key: 'X-Content-Type-Options', value: 'nosniff' },
          { key: 'X-Frame-Options', value: 'DENY' },
          { key: 'X-XSS-Protection', value: '1; mode=block' },
          { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
          { key: 'Permissions-Policy', value: 'camera=(), microphone=(), geolocation=()' },
          { key: 'Content-Security-Policy', value: contentSecurityPolicy },
        ],
      },
      {
        source: '/api/:path*',
        headers: [
          { key: 'Cache-Control', value: 'no-store, no-cache, must-revalidate' },
        ],
      },
    ]
  },
};

export default nextConfig;
